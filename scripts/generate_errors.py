"""Generate ``src/hydraulik/_errors.py`` from the vendored Nogat error registry.

ERR-3: the error module of a project is generated from the copy of
``error_registry.json`` that the project keeps; a contract test
(``tests/contract/test_error_registry.py``) compares the module with this output.

Usage::

    uv run scripts/generate_errors.py            # write the module
    uv run scripts/generate_errors.py --check    # fail when the module is stale
"""

import argparse
import json
import subprocess
import sys
import textwrap
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
REGISTRY = ROOT / "schemas" / "nogat" / "error_registry.json"
MODULE = ROOT / "src" / "hydraulik" / "_errors.py"

_WIDTH = 70  # text per line of a wrapped string literal (indent 12 + quotes <= 88)


def _literal(text: str, indent: int) -> list[str]:
    """Return ``text`` as the lines of one parenthesised string literal."""
    pieces = textwrap.wrap(
        text,
        width=_WIDTH,
        drop_whitespace=False,
        break_long_words=False,
        break_on_hyphens=False,
    )
    pad = " " * indent
    return [f"{pad}{json.dumps(piece, ensure_ascii=True)}" for piece in pieces]


def render(registry: dict[str, Any]) -> str:
    """Return the text of the generated module for ``registry``."""
    lines = [
        '"""Error registry of the Nogat standard (ERR-3), generated.',
        "",
        "Generated by ``scripts/generate_errors.py`` from",
        "``schemas/nogat/error_registry.json``; do not edit.",
        '"""',
        "",
        "from dataclasses import dataclass",
        "from typing import Final, Literal",
        "",
        f"STANDARD_VERSION: Final = {json.dumps(registry['standard_version'])}",
        "",
        "# Outcomes that are not errors (ERR §1): status -> exit code.",
        "OUTCOMES: Final[dict[str, int]] = {",
    ]
    for outcome in registry["outcomes"]:
        lines.append(f'    "{outcome["status"]}": {outcome["exit_code"]},')
    lines += [
        "}",
        "",
        "",
        "@dataclass(frozen=True)",
        "class RegistryCode:",
        '    """One error code of the registry (ERR §2)."""',
        "",
        "    code: str",
        "    exit_code: int | None",
        "    http_status: int | None",
        "    title: str",
        "    title_pl: str",
        "    meaning: str",
        "",
        "",
        "CODES: Final[tuple[RegistryCode, ...]] = (",
    ]
    for entry in registry["errors"]:
        lines += [
            "    RegistryCode(",
            f'        code="{entry["code"]}",',
            f"        exit_code={entry['exit_code']},",
            f"        http_status={entry['http_status']},",
            f"        title={json.dumps(entry['title_en'])},",
            f"        title_pl={json.dumps(entry['title_pl'])},",
            "        meaning=(",
            *_literal(entry["meaning"], 12),
            "        ),",
            "    ),",
        ]
    lines += [
        ")",
        "BY_CODE: Final[dict[str, RegistryCode]] = {c.code: c for c in CODES}",
        "",
        "# Codes a CLI call can end with (REST-only codes have no exit code).",
        "ErrorCodeName = Literal[",
        *[
            f'    "{entry["code"]}",'
            for entry in registry["errors"]
            if entry["exit_code"] is not None
        ],
        "]",
        "",
    ]
    return _formatted("\n".join(lines))


def _formatted(text: str) -> str:
    """Return ``text`` formatted by ruff with the settings of the project."""
    done = subprocess.run(
        [sys.executable, "-m", "ruff", "format", "--stdin-filename", str(MODULE), "-"],
        input=text,
        capture_output=True,
        text=True,
        check=True,
        cwd=ROOT,
    )
    return done.stdout


def main(argv: list[str] | None = None) -> int:
    """Write the module, or with ``--check`` fail when it is stale."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="do not write")
    args = parser.parse_args(argv)
    text = render(json.loads(REGISTRY.read_text(encoding="utf-8")))
    if args.check:
        if MODULE.read_text(encoding="utf-8") != text:
            print(f"{MODULE.relative_to(ROOT)} is stale: run generate_errors.py")
            return 1
        return 0
    MODULE.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
